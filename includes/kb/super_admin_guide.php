    <div class="card-body">
        <h5 class="card-subtitle mb-2">Welcome to the Super Admin Panel!</h5>
        <p>As a Super Admin, you have the highest level of control over the entire platform. This guide outlines your extensive capabilities.</p>

        <hr>

        <h6>1. Full User Management</h6>
        <p>You have unrestricted access to manage all user accounts, including other administrators.</p>
        <ul>
            <li><strong>Manage All Users:</strong> You can add, edit, and delete any user, including Admins and Staff. The only account you cannot delete is your own.</li>
            <li><strong>Assign Roles:</strong> You can promote or demote users by changing their roles.</li>
        </ul>

        <h6>2. Role & Permission Management</h6>
        <p>You are the only role that can define what other users can do.</p>
        <ul>
            <li><strong>Manage Roles:</strong> Create new roles or edit the permissions assigned to existing roles (e.g., Admin, Staff).</li>
            <li><strong>Assign Permissions:</strong> Fine-tune permissions for each role, granting or revoking access to specific features.</li>
        </ul>

        <h6>3. System Settings</h6>
        <p>You control the core configuration of the application.</p>
        <ul>
            <li><strong>General Settings:</strong> Change the site name, configure email (SMTP) settings, and set other global options.</li>
            <li><strong>Landing Page Content:</strong> From the "Manage Landing Page" section, you can edit the text and images that appear on the public homepage for logged-out users.</li>
        </ul>

        <h6>4. Full Test & Question Management</h6>
        <p>You have all the capabilities of an Admin and Staff member regarding tests and questions.</p>
        <ul>
            <li>Create, edit, and delete any test or question.</li>
            <li>Manage categories for the question bank.</li>
        </ul>

        <p class="mt-4"><strong>With great power comes great responsibility.</strong> Please be cautious when changing system settings or role permissions, as these changes can have a significant impact on the user experience.</p>
    </div>
</div>
