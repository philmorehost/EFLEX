        <h5 class="card-subtitle mb-2">Welcome to the Admin Panel!</h5>
        <p>As an Administrator, you have expanded permissions to manage the platform's users and tests. Here’s a detailed guide to your capabilities.</p>

        <hr>

        <h6>1. User Management</h6>
        <p>You can manage all users on the platform, including Staff and regular Users. Super Admins cannot be modified by you.</p>
        <ul>
            <li><strong>View Users:</strong> See a complete list of all users, their roles, and their status.</li>
            <li><strong>Add Users:</strong> Manually create new user accounts and assign them a role.</li>
            <li><strong>Edit Users:</strong> Modify a user's details, change their role, or update their status (e.g., from 'pending' to 'active').</li>
            <li><strong>Delete Users:</strong> Permanently remove a user from the system. This action is irreversible.</li>
        </ul>

        <h6>2. Test Management</h6>
        <p>You have full control over all tests and questions, the same as a Staff member.</p>
        <ul>
            <li><strong>Create, Edit, and Delete Tests.</strong></li>
            <li><strong>Manage the Question Bank:</strong> Add, edit, and delete questions and their categories.</li>
        </ul>

        <h6>3. View Test Results</h6>
        <p>You can view detailed results and analytics for all test attempts made by users, helping you track performance and identify trends.</p>

        <p class="mt-4"><strong>Note:</strong> While you have broad permissions, system-wide settings and role permissions can only be managed by a Super Admin.</p>
    </div>
</div>
