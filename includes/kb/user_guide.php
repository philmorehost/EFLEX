    <div class="card-body">
        <h5 class="card-subtitle mb-2">Welcome to your Dashboard!</h5>
        <p>This is your personal space where you can prepare for your exams. Here’s a quick guide to the features available to you.</p>

        <hr>

        <h6>1. Dashboard Overview</h6>
        <p>Your dashboard provides a summary of your test-taking activity:</p>
        <ul>
            <li><strong>Tests Taken:</strong> The total number of tests you have completed.</li>
            <li><strong>Average Score:</strong> Your average score across all completed tests.</li>
            <li><strong>Tests Passed:</strong> The number of tests where your score was 70% or higher.</li>
        </ul>

        <h6>2. Available Tests</h6>
        <p>This section lists all the tests that are currently available for you to take. Each test card displays:</p>
        <ul>
            <li><strong>Title and Description:</strong> What the test is about.</li>
            <li><strong>Number of Questions:</strong> The total questions in the test.</li>
            <li><strong>Time Limit:</strong> The duration of the test in minutes.</li>
            <li><strong>Closing Date:</strong> If applicable, the last day you can take the test.</li>
        </ul>

        <h6>3. How to Take a Test</h6>
        <p>Taking a test is simple:</p>
        <ol>
            <li>Find the test you want to take in the "Available Tests" section.</li>
            <li>Click the <strong>"Start Test"</strong> button. If you've already started a test and haven't finished, this button will say <strong>"Continue Test"</strong>.</li>
            <li>The test will begin. Read each question carefully and select the correct answer.</li>
            <li>Once you have answered all the questions, click the <strong>"Submit"</strong> button.</li>
        </ol>
        <p><strong>Note:</strong> Once you submit, you cannot change your answers. If a test has a time limit, it will be submitted automatically when the time runs out.</p>

        <h6>4. Viewing Your Score</h6>
        <p>After completing a test, your score will be displayed on the test card on your dashboard, marked with a "Test Completed" badge.</p>

        <h6>5. Managing Your Profile</h6>
        <p>You can update your personal information and change your profile picture from the <strong>"Profile"</strong> page. A link to your profile can be found in the navigation menu.</p>

        <h6>6. Logging Out</h6>
        <p>To log out of your account, simply click the <strong>"Logout"</strong> button on your dashboard.</p>
    </div>
</div>
