        <h5 class="card-subtitle mb-2">Welcome to the Admin Panel!</h5>
        <p>As a Staff member, you have specific permissions to help manage the testing process. Here’s what you can do.</p>

        <hr>

        <h6>1. Dashboard Overview</h6>
        <p>Your dashboard provides a quick summary of the platform's key metrics, including total tests, questions, and users.</p>

        <h6>2. Managing Tests</h6>
        <p>You have full control over the tests and questions in the system.</p>
        <ul>
            <li><strong>View Tests:</strong> See a list of all tests, their status, and the number of questions they contain.</li>
            <li><strong>Create Tests:</strong> Click the "Add New Test" button to create a new test. You will need to provide a title, description, time limit, and availability dates.</li>
            <li><strong>Edit Tests:</strong> You can modify the details of any existing test.</li>
            <li><strong>Add Questions to a Test:</strong> After creating a test, you can add questions to it from the Question Bank.</li>
        </ul>

        <h6>3. Managing the Question Bank</h6>
        <p>The Question Bank is the central repository for all questions.</p>
        <ul>
            <li><strong>View Questions:</strong> Browse all questions, categorized by subject and exam body.</li>
            <li><strong>Create Questions:</strong> Add new questions of different types (Multiple Choice, True/False, etc.) and specify the correct answers.</li>
        </ul>

        <p class="mt-4"><strong>Note:</strong> Your permissions are limited to test and question management. For user or system-level changes, please contact an Administrator or Super Admin.</p>
    </div>
</div>
